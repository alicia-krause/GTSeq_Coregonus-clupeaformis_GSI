# =========================================
# GTscore amplicon genotyping and SNP quality-control workflow
# Dataset: Lake whitefish (Coregonus clupeaformis) GT-seq data (project prefix: Cclu_2204_R1)
# GTscore toolkit: McKinney et al. 2020, local GTscore.R v1.3
# =========================================

# 00 | Pre-processing (run in command line sequenced data directory, outside R)

# 1. Generate sample list file in CMD using ls *.fastq >> sampleFiles.txt 
# 2. Count amplicon sequence reads associated with primer/probe and sample list files using perl AmpliconReadCounter.pl -p Cclu_Primer_Probe_File_n457.txt --files sampleFiles.txt --prefix Cclu_2204_R1_ # Count amplicon sequence reads associated with primer/probe and sample list files
# IMPORTANT: AmpliconReadCounter.pl and Cclu_Primer_Probe_File_n457.txt are prerequisites, not generated by this script

# Setup
library(dplyr)
library(ggplot2)
library(tidyr)
library(pbapply)

source("./GTscore.R")  # Load GTscore toolkit
geno_threshold = 0.8 # Minimum retained locus genotyping rate
dir.create("./analysis", showWarnings = FALSE) #Create output directory
# =========================================


# 01 | Genotyping (Load locus metadata and allele read counts from AmpliconReadCounter; check locus IDs)

singleSNP_locusTable<-read.delim("./Cclu_2204_R1_LocusTable_singleSNPs.txt",
                                 header=TRUE,
                                 stringsAsFactors=FALSE)

singleSNP_alleleReads<-read.delim("./Cclu_2204_R1_AlleleReads_singleSNPs.txt",
                                  header=TRUE,
                                  row.names=1,
                                  check.names=FALSE,
                                  stringsAsFactors=FALSE)

# Generate singleSNP genotypes from allele counts using the polyGen algorithm (average run time: 1.5 hours for 5500 samples)
polyGenResults_singleSNP<-polyGen(singleSNP_locusTable,
                                  singleSNP_alleleReads)

# Output polyGen results
write.table(polyGenResults_singleSNP, "./analysis/Cclu_2204_R1_polyGenResults_singleSNP.txt",
            quote=FALSE,
            sep="\t")

# Export polyGenResults_singleSNP.txt as genepop file (run separate)
exportation(polyGenResults_singleSNP,singleSNP_locusTable, filename="Cclu_2204_R1_polyGenResults_singleSNP_genepop.txt", exportParalogs=FALSE)


# ====
#### Shortcut IF polyGen singlSNP files were previously generated (Skips code on line 38)####
polyGenResults_singleSNP = read.delim("./analysis/Cclu_2204_R1_polyGenResults_singleSNP.txt", 
                                      header= TRUE, 
                                      row.names=1, 
                                      check.names=FALSE, 
                                      stringsAsFactors=FALSE)
# =========================================


# 02 | Summarize unfiltered sample quality

# Load sample summary from AmpliconReadCounter.pl
GTscore_individualSummary <- read.delim("./Cclu_2204_R1_GTscore_individualSummary.txt",
                                        header = TRUE,
                                        stringsAsFactors = FALSE)

# Summarize  single SNP results for samples (join sample-level results to original AmpliconReadCounter.pl summaries)
singleSNP_sampleSummary = summarizeSamples(polyGenResults_singleSNP, singleSNP_alleleReads)

# Combine AmplicaonRead Counter.pl individual summaries with GTscore sample summary
GTscore_individualSummary <- merge(GTscore_individualSummary,
                                   singleSNP_sampleSummary,
                                   by.x = "Sample",
                                   by.y = "sample")

# Output summary table
write.table(GTscore_individualSummary, "./analysis/Cclu_2204_R1_GTscore_individualSummary2.txt",
            quote = FALSE,
            sep = "\t",
            row.names = FALSE)

# Summarize singleSNP results for loci (average run time: 15 min for 5500 samples)
singleSNP_summary <- summarizeGTscore(singleSNP_alleleReads, singleSNP_locusTable, polyGenResults_singleSNP)

# rite out resulting singleSNP summary table
write.table(singleSNP_summary, "./analysis/singleSNP_summary.txt",
            quote = FALSE,
            sep = "\t",
            row.names = FALSE)
# =========================================


